// Writes the `subhost` service into docker-compose.template.yml, with the host
// program (host.mjs) and the container spec (probe.base.json plus probe.mjs)
// embedded as base64. The deployed compose file is measured into the CVM's
// attestation, so this puts the exact host code and container spec under it.
//
//   node subhost/embed.mjs           update the template
//   node subhost/embed.mjs --check   fail if the template is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { canonicalJson, codeHash, validateSpec } from './host.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const NODE_IMAGE = 'docker.io/library/node:22-alpine@sha256:0e1754758c2df4cfa3e68d59e2e1b7374bb7fd9ea6328eaaacf15cc934af8202';
export const BEGIN = '  # BEGIN subhost: generated by `node subhost/embed.mjs`. Do not edit by hand.';
export const END = '  # END subhost';

const lf = text => text.replace(/\r\n/g, '\n');
const readText = (root, file) => lf(readFileSync(join(root, file), 'utf8'));

/** The spec the host runs: the base settings plus probe.mjs as the command. */
export function probeSpec(root = ROOT) {
  const base = JSON.parse(readText(root, 'subhost/probe.base.json'));
  return validateSpec({ ...base, cmd: ['node', '--input-type=module', '-e', readText(root, 'subhost/probe.mjs')] });
}

export function subhostBlock(root = ROOT) {
  const hostB64 = Buffer.from(readText(root, 'subhost/host.mjs'), 'utf8').toString('base64');
  const specB64 = Buffer.from(canonicalJson(probeSpec(root)), 'utf8').toString('base64');
  return [
    BEGIN,
    '  # The only service, with the two TLS ingress containers, that mounts dstack\'s',
    '  # socket. It gives Router its two keys and runs one attested sub-container.',
    '  # See subhost/README.md.',
    '  subhost:',
    `    image: ${NODE_IMAGE}`,
    '    command:',
    '      - node',
    '      - --input-type=module',
    '      - -e',
    `      - "import('data:text/javascript;base64,${hostB64}')"`,
    '    environment:',
    '      - SUBHOST_MAIN=1',
    `      - SUBHOST_PROBE_SPEC=${specB64}`,
    '    volumes:',
    '      - /var/run/dstack.sock:/var/run/dstack.sock',
    '      - /var/run/docker.sock:/var/run/docker.sock',
    '      - /var/run/subhost:/var/run/subhost',
    '    ports:',
    '      - "8091:8091"',
    '    healthcheck:',
    '      test: ["CMD", "node", "-e", "fetch(\'http://127.0.0.1:8091/health\').then(r => process.exit(r.ok ? 0 : 1), () => process.exit(1))"]',
    '      interval: 5s',
    '      timeout: 3s',
    '      retries: 24',
    '      start_period: 5s',
    '    stop_grace_period: 15s',
    '    restart: unless-stopped',
    '    logging:',
    '      driver: json-file',
    '      options:',
    '        max-size: "10m"',
    '        max-file: "3"',
    END,
  ].join('\n');
}

/** Replaces the block between the markers. Line endings follow the template's. */
export function withBlock(templateText, block) {
  const eol = templateText.includes('\r\n') ? '\r\n' : '\n';
  const text = lf(templateText);
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error('subhost markers not found in docker-compose.template.yml');
  return (text.slice(0, start) + block + text.slice(end + END.length)).replace(/\n/g, eol);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = join(ROOT, 'docker-compose.template.yml');
  const current = readFileSync(file, 'utf8');
  const next = withBlock(current, subhostBlock());
  if (process.argv.includes('--check')) {
    if (lf(next) !== lf(current)) { console.error('docker-compose.template.yml is out of date: run node subhost/embed.mjs'); process.exit(1); }
    console.log(`subhost block is current; container code hash ${codeHash(probeSpec())}`);
  } else {
    writeFileSync(file, next);
    console.log(`updated docker-compose.template.yml; container code hash ${codeHash(probeSpec())}`);
  }
}

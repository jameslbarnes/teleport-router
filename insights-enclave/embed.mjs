// Writes the `gate` service into docker-compose.insights-enclave.yml, with gate.mjs embedded as base64.
// The deployed compose file is measured into the CVM's attestation, so this puts the exact gate code, and
// the network layout that makes it the only way out, under it.
//
//   node insights-enclave/embed.mjs           update the compose file
//   node insights-enclave/embed.mjs --check   fail if the compose file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const COMPOSE = 'docker-compose.insights-enclave.yml';
export const NODE_IMAGE = 'docker.io/library/node:22-alpine@sha256:0e1754758c2df4cfa3e68d59e2e1b7374bb7fd9ea6328eaaacf15cc934af8202';
export const BEGIN = '  # BEGIN gate: generated by `node insights-enclave/embed.mjs`. Do not edit by hand.';
export const END = '  # END gate';

const lf = text => text.replace(/\r\n/g, '\n');

export function gateBlock(root = ROOT) {
  const b64 = Buffer.from(lf(readFileSync(join(root, 'insights-enclave/gate.mjs'), 'utf8')), 'utf8').toString('base64');
  return [
    BEGIN,
    '  # The only container with a route out. It passes the enclave\'s five requests in, and one kind of',
    '  # request out: a message to the model named below. See insights-enclave/gate.mjs.',
    '  gate:',
    `    image: ${NODE_IMAGE}`,
    '    command:',
    '      - node',
    '      - --input-type=module',
    '      - -e',
    `      - "import('data:text/javascript;base64,${b64}')"`,
    '    environment:',
    '      - INSIGHTS_GATE=run',
    '      - INSIGHTS_MODEL=claude-sonnet-5-5',
    '      - APP_URL=http://insights-enclave:3100',
    '      - IN_PORT=3100',
    '      - OUT_PORT=8089',
    '      # Name only: the value comes from Phala\'s encrypted environment at deploy time.',
    '      - ANTHROPIC_API_KEY',
    '    ports:',
    '      - "3100:3100"',
    '    networks:',
    '      - sealed',
    '      - default',
    '    restart: unless-stopped',
    END,
  ].join('\n');
}

/** Replaces the block between the markers. Line endings follow the file's. */
export function withBlock(text, block) {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const t = lf(text);
  const start = t.indexOf(BEGIN), end = t.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`gate markers not found in ${COMPOSE}`);
  return (t.slice(0, start) + block + t.slice(end + END.length)).replace(/\n/g, eol);
}

/** The gate program a compose file carries, decoded. */
export function embeddedGate(composeText) {
  const m = /import\('data:text\/javascript;base64,([A-Za-z0-9+/=]+)'\)/.exec(composeText);
  return m ? Buffer.from(m[1], 'base64').toString('utf8') : null;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = join(ROOT, COMPOSE);
  const current = readFileSync(file, 'utf8');
  const next = withBlock(current, gateBlock());
  if (process.argv.includes('--check')) {
    if (lf(next) !== lf(current)) { console.error(`${COMPOSE} is out of date: run node insights-enclave/embed.mjs`); process.exit(1); }
    console.log('gate block is current');
  } else {
    writeFileSync(file, next);
    console.log(`updated ${COMPOSE}`);
  }
}
